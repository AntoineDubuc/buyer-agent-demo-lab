def _strat(sec: dict[str, Any], name: str) -> dict[str, Any]:
    return ((sec or {}).get("strategies") or {}).get(name) or {}


def _cell_stats(env: dict[str, Any], pid: str | None) -> str:
    if not env:
        return '<td colspan="3" class="muted">Not run</td>'
    if env.get("status") != "ok":
        return f'<td colspan="3">{pill(env.get("status"), env.get("reason") or None)}</td>'
    summ = env.get("summary") or {}
    s = (summ.get("per_personality") or {}).get(pid) if pid else summ.get("total")
    if not s:
        return '<td colspan="3" class="muted">-</td>'
    cpm = f'${s["avg_final_cpm"]:.2f}' if s.get("avg_final_cpm") is not None else "-"
    return (f'<td class="num">{s.get("won", 0)} of {s.get("deals", 0)}</td><td class="num">{cpm}</td>'
            f'<td class="num">{s.get("avg_rounds", "-")}</td>')


def _transcript(env: dict[str, Any], pid: str) -> str:
    if not env or env.get("status") not in ("ok", "error"):
        return ""
    for s in env.get("showcase") or []:
        if s.get("personality") == pid:
            rows = "".join(f'<tr><td class="num">{r.get("round")}</td><td class="num">${r.get("buyer", 0):.2f}</td>'
                           f'<td class="num">${r.get("seller", 0):.2f}</td><td>{E(str(r.get("action")))}</td></tr>'
                           for r in s.get("rounds") or [])
            final = f'${s["final_price"]:.2f}' if s.get("final_price") is not None else "no deal"
            body = (f'<table><tr><th class="num">Round</th><th class="num">We offered</th><th class="num">Seller asked</th>'
                    f"<th>Seller move</th></tr>{rows}</table>" if rows else "")
            return f'<p>Outcome: <b>{E(str(s.get("outcome")))}</b>, price {E(final)}. {E(s.get("reason", ""))}</p>{body}'
    return ""


def render_negotiation(b: dict | None, a: dict | None) -> tuple[str, str, str]:
    bs, as_ = section(b) or {}, section(a) or {}
    ref = bs or as_
    pers = ref.get("personalities") or []
    bsimple, asimple, aadapt = _strat(bs, "simple"), _strat(as_, "simple"), _strat(as_, "adaptive")
    badapt = _strat(bs, "adaptive")
    head = ('<tr><th rowspan="2">Seller personality</th><th colspan="3">Before: today\'s negotiator</th>'
            '<th colspan="3">After: today\'s negotiator</th><th colspan="3">After: adaptive negotiator</th></tr>'
            '<tr>' + '<th class="num">Deals won</th><th class="num">Avg price</th><th class="num">Avg rounds</th>' * 3 + "</tr>")
    body = []
    for p in pers:
        pid = p.get("id")
        body.append(f'<tr><td><b>{E(p.get("title", pid))}</b><br><span class="muted">{E(p.get("plain", ""))}</span></td>'
                    f"{_cell_stats(bsimple, pid)}{_cell_stats(asimple, pid) if as_ else '<td colspan=3 class=muted>Not run</td>'}"
                    f"{_cell_stats(aadapt, pid) if as_ else '<td colspan=3 class=muted>Not run</td>'}</tr>")
    body.append(f"<tr><td><b>All {E(str((ref.get('tournament') or {}).get('deals', '')))} deals</b></td>"
                f"{_cell_stats(bsimple, None)}{_cell_stats(asimple, None) if as_ else '<td colspan=3 class=muted>Not run</td>'}"
                f"{_cell_stats(aadapt, None) if as_ else '<td colspan=3 class=muted>Not run</td>'}</tr>")
    table = f'<div class="scroll"><table>{head}{"".join(body)}</table></div>'

    # Regression check: today's negotiator must behave identically on both sides.
    reg = ""
    if bsimple.get("status") == "ok" and asimple.get("status") == "ok":
        key = lambda env: [(d["deal_id"], d["outcome"], d["final_price"], len(d["rounds"])) for d in env.get("deals") or []]  # noqa: E731
        same = key(bsimple) == key(asimple)
        reg = (f'<p>{pill("ok" if same else "error", "Same results" if same else "Different results")} '
               "Regression check: today's negotiator gives deal-for-deal identical results before and after.</p>")
    adapt_note = ""
    if badapt:
        adapt_note = (f'<p class="muted">Adaptive negotiator before the change: {pill(badapt.get("status"), badapt.get("reason"))} '
                      f'{E(str((badapt.get("detection") or {}).get("import_path", "")))}</p>')

    tx = []
    for p in pers:
        pid = p.get("id")
        cols = (side_html("Before: today's negotiator", _transcript(bsimple, pid) or not_run_cell(None))
                + side_html("After: adaptive negotiator", _transcript(aadapt, pid) or (
                    f'{pill(aadapt.get("status"), aadapt.get("reason"))}' if aadapt else not_run_cell(a))))
        tx.append(f'<details><summary>Round by round: {E(p.get("title", pid))}</summary><div class="cols">{cols}</div></details>')

    found = acceptance.notes("negotiation", a)
    honest = ("<p><b>Where the adaptive negotiator does not do better (measured on this run):</b></p><ul>"
              + "".join(f"<li>{E(n)}</li>" for n in found) + "</ul>") if found else ""
    cards = (f'<section class="card"><h2>{E(str((ref.get("tournament") or {}).get("deals", "")))} simulated deals, '
             f"six seller personalities</h2><p>Same sellers, same seed, both sides. Price is CPM: what we pay per "
             f"thousand impressions; lower is better. Deals that did not close have no price.</p>"
             f"{table}{reg}{adapt_note}"
             '<p class="expect"><b>What the lab expects after the change:</b> the adaptive negotiator closes deals with '
             "the seller that takes any offer at its floor (today's negotiator walks away from it), lands a lower "
             "average price with the proportional conceder while winning the same deals, never pays above $30, and "
             "leaves today's negotiator unchanged. It is <b>not</b> expected to win everywhere: against the firm "
             "seller it closes slightly fewer deals, against the \"stubborn, then caves\" seller neither negotiator "
             "closes, and against the wall seller nobody can close.</p>"
             f"{honest}</section>"
             f'<section class="card"><h2>Round-by-round examples</h2><p class="muted">One seller of each personality at '
             f"its exact settings.</p>{''.join(tx)}</section>")
    raw = {"before": {k: v for k, v in bs.items() if k != "strategies"} if bs else None}
    cards += f'<section class="card">{raw_block(raw, "Raw settings")}</section>'
    return cards, bs.get("headline", ""), as_.get("headline", "")


