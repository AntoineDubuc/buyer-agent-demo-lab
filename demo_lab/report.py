def footer(b: dict | None, a: dict | None) -> str:
    def one(label: str, d: dict | None) -> str:
        if not d or "buyer_agent" not in d:
            return f"<li>{E(label)}: not run</li>"
        ba = d["buyer_agent"]
        net = (d.get("network") or {}).get("outbound_attempts_blocked") or []
        folder = Path(str(ba.get("dir") or "")).name or "unknown"
        return (f'<li>{E(label)}: buyer agent checkout <code>{E(folder)}</code>, branch '
                f'{E(str(ba.get("git_branch")))}, commit {E(str(ba.get("git_sha"))[:12])}, '
                f'{E(str(ba.get("uncommitted_files")))} uncommitted files; Python {E(str(ba.get("python")))}; '
                f'run {E(str(d.get("started_at", ""))[:19])} UTC; lab {E(str((d.get("lab") or {}).get("version")))}; '
                f"network attempts blocked: {len(net)}.</li>")
    return (f"<footer><p>How this was produced: the demo lab drove the buyer agent's own code in-process, with a "
            f"throw-away database and all network access switched off. No AI service was called.</p><ul>"
            f"{one('Before', b)}{one('After', a)}</ul></footer>")


def acceptance_card(change: str, before: dict | None, after: dict | None) -> str:
    """Pass/fail table: the same criteria as `python -m demo_lab.check`, on both sides."""
    sides = [(lbl, acceptance.evaluate(change, d)) for lbl, d in (("Before", before), ("After", after))
             if section(d) is not None]
    if not sides:
        return ""
    crit = list(dict.fromkeys(c.criterion for _, cs in sides for c in cs))
    by = [{c.criterion: c for c in cs} for _, cs in sides]

    def cell(c: acceptance.Check | None) -> str:
        if c is None:
            return '<td class="muted">-</td>'
        return (f'<td>{pill("ok" if c.ok else "error", "PASS" if c.ok else "FAIL")} '
                f'<span class="muted">{E(c.observed)}</span></td>')

    rows = "".join(f"<tr><td>{E(k)}</td>{''.join(cell(m.get(k)) for m in by)}</tr>" for k in crit)
    verdict = "".join(
        f'<p>{E(lbl)}: {pill("ok" if acceptance.passed(cs) else "error", "PASS" if acceptance.passed(cs) else "FAIL")} '
        f'<span class="muted">{sum(c.ok for c in cs)} of {len(cs)} criteria pass</span></p>' for lbl, cs in sides)
    head = "".join(f"<th>{E(lbl)}</th>" for lbl, _ in sides)
    return (f'<section class="card"><h2>Acceptance check</h2><p class="muted">The same criteria as '
            f'<code>./acceptance.sh &lt;checkout&gt; {E(change)}</code>. The change passes only if every line passes.</p>'
            f'{verdict}<div class="scroll"><table><tr><th>Criterion</th>{head}</tr>{rows}</table></div></section>')


def render(change: str, before: dict | None, after: dict | None) -> str:
    meta = PAGES[change]
    fn = {"pacing": render_pacing, "creatives": render_creatives, "negotiation": render_negotiation}[change]
    try:
        cards, bh, ah = fn(before, after)
    except Exception as exc:  # noqa: BLE001 - the page must still render
        cards, bh, ah = f'<section class="card">{pill("error")} Renderer could not read the results: {E(str(exc))}</section>', "", ""
    for d, side in ((before, "before"), (after, "after")):
        sec = section(d)
        if sec and sec.get("status") == "error":
            cards = (f'<section class="card">{pill("error")} The {side} run failed as a whole: '
                     f'{E(str(sec.get("reason")))}{raw_block(sec)}</section>') + cards
    summary = (f'<section class="card summary"><h2>In one line</h2><div class="cols">'
               f'{side_html("Before (today)", f"<p class=headline>{E(bh)}</p>" if bh else not_run_cell(before if not section(before) else None))}'
               f'{side_html("After (with the change)", f"<p class=headline>{E(ah)}</p>" if ah else not_run_cell(after))}'
               "</div></section>")
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8">'
            f'<meta name="viewport" content="width=device-width,initial-scale=1">'
            f"<title>{E(change.capitalize())} Before After</title><style>{CSS}</style></head><body><main>"
            f'<p class="muted">Buyer agent demo lab - a sample performance-media campaign</p><h1>{E(meta["title"])}</h1>'
            f'<p>{E(meta["what"])}</p><div class="label">{E(meta["honesty"])}</div>'
            f"{summary}{acceptance_card(change, before, after)}{cards}{footer(before, after)}</main></body></html>")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="demo_lab.report")
    ap.add_argument("--before", required=True)
    ap.add_argument("--after", default=None)
    ap.add_argument("--change", required=True, choices=list(PAGES))
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    page = render(a.change, load(a.before), load(a.after))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
