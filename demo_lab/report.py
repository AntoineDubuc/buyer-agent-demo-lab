def pill(status: str | None, text: str | None = None) -> str:
    cls = {"ok": "ok", "not_available": "na", "error": "err"}.get(status or "", "na")
    txt = text or {"ok": "Ran", "not_available": "Not in this version", "error": "Error"}.get(status or "", "Not run")
    return f'<span class="pill {cls}">{E(txt)}</span>'


def raw_block(obj: Any, label: str = "Raw result") -> str:
    return f"<details><summary>{E(label)}</summary><pre>{E(json.dumps(obj, indent=2, default=str))}</pre></details>"


def money(x: Any) -> str:
    try:
        return f"${float(x):,.2f}"
    except (TypeError, ValueError):
        return "-"


def load(path: str | None) -> dict[str, Any] | None:
    if not path:
        return None
    p = Path(path)
    if not p.exists():
        return {"_missing": str(p)}
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except ValueError as exc:
        return {"_unreadable": f"{p}: {exc}"}


def section(doc: dict[str, Any] | None) -> dict[str, Any] | None:
    if not doc or "result" not in doc:
        return None
    return doc["result"] if isinstance(doc["result"], dict) else None


def not_run_cell(doc: dict[str, Any] | None) -> str:
    if doc and doc.get("_missing"):
        why = f"Results file not found: {doc['_missing']}"
    elif doc and doc.get("_unreadable"):
        why = f"Results file unreadable: {doc['_unreadable']}"
    else:
        why = "This side has not been run yet."
    return f'{pill(None, "Not run")}<p class="muted">{E(why)}</p>'


def side_html(title: str, body: str) -> str:
    return f'<div class="side"><h3>{E(title)}</h3>{body}</div>'


# ---------------------------------------------------------------- pacing


def pacing_side(row: dict[str, Any] | None) -> str:
    if row is None:
        return not_run_cell(None)
    if row.get("status") == "error":
        return f'{pill("error")}<p class="headline">{E(row.get("headline") or "")}</p>{raw_block(row)}'
    out = [f'<p class="headline">{E(row.get("headline") or headlines.pacing(row))}</p>']
    rp, cp = row.get("run_pacing_check") or {}, row.get("check_pacing") or {}
    out.append(f'<p class="muted">Pacing check tool: {pill(rp.get("status"))} &nbsp; '
               f'Pacing report tool: {pill(cp.get("status"))}</p>')
    _, res = headlines.pacing_result(row)
    chans = res.get("channel_pacing") if isinstance(res, dict) else None
    if chans:
        rows = "".join(
            f'<tr><td>{E(headlines.ch_name(c.get("channel")))}</td><td class="num">{money(c.get("spend"))}</td>'
            f'<td class="num">{money(c.get("expected_spend"))}</td>'
            f'<td class="num">{E(str(c.get("pacing_pct", "-")))}%</td><td>{E(str(c.get("status", "-")))}</td></tr>'
            for c in chans)
        out.append('<div class="scroll"><table><tr><th>Channel</th><th class="num">Spent</th>'
                   '<th class="num">Should have spent</th><th class="num">Pace</th><th>Agent says</th></tr>'
                   f"{rows}</table></div>")
    if isinstance(res, dict):
        recs = res.get("recommendations")
        if recs:
            items = "".join(
                f'<li>Move {money(r.get("amount"))} from {E(headlines.ch_name(r.get("source_channel")))} to '
                f'{E(headlines.ch_name(r.get("target_channel")))}. <span class="muted">{E(str(r.get("reason", "")))}'
                f"</span></li>" for r in recs if isinstance(r, dict))
            out.append(f"<p>Recommendations:</p><ul>{items}</ul>")
        elif chans or res.get("status") == "no_delivery_data":
            out.append("<p>Recommendations: none.</p>")
        if res.get("pacing_status"):
            out.append(f'<p class="muted">Overall campaign status: {E(str(res["pacing_status"]))}</p>')
        if res.get("summary"):
            out.append(f'<p class="muted">Agent summary: {E(str(res["summary"]))}</p>')
    out.append(raw_block({"run_pacing_check": rp, "check_pacing": cp}, "Raw tool answers"))
    return "".join(out)


def pacing_input(row: dict[str, Any]) -> str:
    inp = row.get("input") or {}
    if not inp:
        return ""
    if all(v.get("pace_pct") is None for v in inp.values()):
        return '<p class="muted">What we fed in: no delivery numbers for this campaign.</p>'
    rows = "".join(
        f'<tr><td>{E(headlines.ch_name(ch))}</td><td class="num">{money(v.get("allocated_budget"))}</td>'
        f'<td class="num">{money(v.get("expected_spend"))}</td><td class="num">{money(v.get("spend"))}</td>'
        f'<td class="num">{E(str(v.get("pace_pct")))}%</td></tr>' for ch, v in inp.items())
    return ('<p class="muted">What we fed in (same on both sides):</p><div class="scroll"><table><tr><th>Channel</th>'
            '<th class="num">Budget</th><th class="num">Should have spent by Aug 15</th><th class="num">Actually spent</th>'
            f'<th class="num">Pace</th></tr>{rows}</table></div>')


def render_pacing(b: dict | None, a: dict | None) -> tuple[str, str, str]:
    bs, as_ = section(b) or {}, section(a) or {}
    bmap = {r["id"]: r for r in bs.get("scenarios") or [] if isinstance(r, dict) and "id" in r}
    amap = {r["id"]: r for r in as_.get("scenarios") or [] if isinstance(r, dict) and "id" in r}
    ids = list(dict.fromkeys([*bmap, *amap]))
    cards = []
    for sid in ids:
        ref = bmap.get(sid) or amap.get(sid)
        cards.append(
            f'<section class="card"><h2>{E(ref.get("title", sid))}</h2><p>{E(ref.get("description", ""))}</p>'
            f"{pacing_input(ref)}"
            f'<div class="cols">{side_html("Before (today)", pacing_side(bmap.get(sid)) if b else not_run_cell(b))}'
            f'{side_html("After (with the change)", pacing_side(amap.get(sid)) if section(a) else not_run_cell(a))}</div>'
            f'<p class="expect"><b>What the lab expects after the change:</b> {E(ref.get("expect_after", ""))}</p></section>')
    key = "ctv_cant_spend"
    return ("".join(cards), (bmap.get(key) or {}).get("headline", ""), (amap.get(key) or {}).get("headline", ""))


# ---------------------------------------------------------------- creatives


def creative_side(row: dict[str, Any] | None) -> str:
    if row is None:
        return not_run_cell(None)
    if row.get("status") == "error":
        return f'{pill("error")}<p class="headline">{E(row.get("headline") or "")}</p>{raw_block(row)}'
    ready = row.get("became_ready")
    mr = row.get("mark_ready") or {}
    vc = row.get("validation_call") or {}
    out = [f'<p class="headline">{E(row.get("headline") or headlines.creatives(row))}</p>',
           f'<p>{pill("ok" if not ready else "error", "Reached READY" if ready else "Held back from READY")} '
           f'<span class="muted">final status: {E(str(row.get("final_status")))}</span></p>',
           f'<p class="muted">Creative check tool: {pill(vc.get("status"))}</p>']
    if mr.get("raised"):
        out.append(f'<p class="muted">Why it was held back:</p><pre>{E(str(mr.get("message", "")))}</pre>')
    rows = []
    for a in row.get("assets") or []:
        st = str(a.get("product_status") or "none")
        cls = {"valid": "ok", "invalid": "err"}.get(st.lower(), "na")
        reasons = a.get("product_reasons")
        if isinstance(reasons, list):
            reasons_txt = "; ".join(str(x) for x in reasons) or "-"
        else:
            reasons_txt = str(reasons) if reasons else "-"
        rows.append(f'<tr><td>{E(a.get("asset_name") or "")}</td><td><span class="pill {cls}">{E(st)}</span></td>'
                    f"<td>{E(reasons_txt)}</td></tr>")
    out.append('<div class="scroll"><table><tr><th>Ad</th><th>Agent status</th><th>Agent reason</th></tr>'
               f'{"".join(rows)}</table></div>')
    out.append(raw_block(row, "Raw result"))
    return "".join(out)


def creative_fixtures(ref: dict[str, Any]) -> str:
    rows = "".join(
        f'<tr><td>{E(a.get("asset_name") or "")}</td><td>{E(headlines.ch_name(a.get("channel")))} / {E(str(a.get("slot")))}</td>'
        f'<td>{E(a.get("lab_expected_problem") or "None - this one is fine")}</td></tr>'
        for a in ref.get("assets") or [])
    return ('<p class="muted">The ads we attached (the problem column is the lab\'s own label, never shown to the agent):</p>'
            '<div class="scroll"><table><tr><th>Ad</th><th>Channel / slot</th><th>Known problem</th></tr>'
            f"{rows}</table></div>")


